// Position (AU) and velocity (AU/day) at a Julian date. Between the yearly states this uses cubic Hermite
// interpolation, which matches Horizons to within a few hundred km for ships coasting this smoothly.
export function stateAt(id, jd) {
  const rows = STATES[id];
  const first = rows[0], last = rows[rows.length - 1];
  if (jd >= last[0]) return coast(last, jd);
  if (jd <= first[0]) return coast(first, jd);
  let i = Math.min(Math.floor((jd - first[0]) / 365.25), rows.length - 2);
  while (rows[i][0] > jd) i--;
  while (rows[i + 1][0] < jd) i++;
  const a = rows[i], b = rows[i + 1], h = b[0] - a[0], s = (jd - a[0]) / h;
  const h00 = 2 * s ** 3 - 3 * s ** 2 + 1, h10 = s ** 3 - 2 * s ** 2 + s, h01 = -2 * s ** 3 + 3 * s ** 2, h11 = s ** 3 - s ** 2;
  const d00 = (6 * s ** 2 - 6 * s) / h, d10 = 3 * s ** 2 - 4 * s + 1, d01 = (-6 * s ** 2 + 6 * s) / h, d11 = 3 * s ** 2 - 2 * s;
  const pos = [], vel = [];
  for (let k = 0; k < 3; k++) {
    pos.push(h00 * a[k + 1] + h10 * h * a[k + 4] + h01 * b[k + 1] + h11 * h * b[k + 4]);
    vel.push(d00 * a[k + 1] + d10 * a[k + 4] + d01 * b[k + 1] + d11 * b[k + 4]);
  }
  return { pos, vel };
}
// Beyond the table, they coast in a straight line, which is near enough for decades.
function coast(row, jd) {
  const dt = jd - row[0];
  return { pos: [0, 1, 2].map(k => row[k + 1] + row[k + 4] * dt), vel: row.slice(4, 7) };
}

// Where a probe has been from launch until a date, for drawing its path.
export function trackUntil(id, jd) {
  const pts = [...parseTrack(TRACKS[id]), ...STATES[id].map(r => [r[0], r[1], r[2], r[3]])]
    .filter(p => p[0] < jd).map(p => p.slice(1));
  pts.push(stateAt(id, jd).pos);
  return pts;
}

