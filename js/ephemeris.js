export const PLANETS = Object.keys(ELEMENTS);
export const semiMajor = name => ELEMENTS[name][0][0];

export function planetAt(name, jd) {
  const T = (jd - 2451545) / 36525;
  const [a, e, I, L, w, O] = ELEMENTS[name].map(([v, rate]) => v + rate * T);
  const peri = w - O;
  let M = ((L - w) % 360 + 540) % 360 - 180;
  M *= DEG;
  let E = M + e * Math.sin(M);
  for (let k = 0; k < 6; k++) E -= (E - e * Math.sin(E) - M) / (1 - e * Math.cos(E));
  const xp = a * (Math.cos(E) - e), yp = a * Math.sqrt(1 - e * e) * Math.sin(E);
  const cw = Math.cos(peri * DEG), sw = Math.sin(peri * DEG), cO = Math.cos(O * DEG), sO = Math.sin(O * DEG), cI = Math.cos(I * DEG), sI = Math.sin(I * DEG);
  return [
    (cw * cO - sw * sO * cI) * xp + (-sw * cO - cw * sO * cI) * yp,
    (cw * sO + sw * cO * cI) * xp + (-sw * sO + cw * cO * cI) * yp,
    (sw * sI) * xp + (cw * sI) * yp,
  ];
}
export const earthAt = jd => planetAt('earth', jd);

// The Moon, roughly (a degree or so): its distance from Earth in km and direction, for the near-Earth view.
export function moonAt(jd) {
  const d = jd - 2451545;
  const L = (218.316 + 13.176396 * d) * DEG, M = (134.963 + 13.064993 * d) * DEG, F = (93.272 + 13.229350 * d) * DEG;
  const lon = L + 6.289 * DEG * Math.sin(M), lat = 5.128 * DEG * Math.sin(F), r = 385001 - 20905 * Math.cos(M);
  return [r * Math.cos(lat) * Math.cos(lon), r * Math.cos(lat) * Math.sin(lon), r * Math.sin(lat)];
}

// ---------- JWST ----------

// Webb's position from Earth's centre in km. Between the table's points it uses a Catmull-Rom curve; outside the
// table it sits at the L2 point itself, 1.5 million km straight out from the Sun.
export function jwstFromEarth(jd) {
  const f = (jd - JWST_START) / JWST_STEP;
  if (f < 0 || f > JWST.length - 1) {
    const e = earthAt(jd), r = Math.hypot(...e);
    return e.map(v => v / r * 1.5e6);
  }
  const i = Math.min(Math.floor(f), JWST.length - 2), s = f - i;
  const p0 = JWST[Math.max(i - 1, 0)], p1 = JWST[i], p2 = JWST[i + 1], p3 = JWST[Math.min(i + 2, JWST.length - 1)];
  return [0, 1, 2].map(k => 0.5 * ((2 * p1[k]) + (-p0[k] + p2[k]) * s + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * s * s + (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * s ** 3));
}
export const jwstSpan = () => [JWST_START, JWST_START + JWST_STEP * (JWST.length - 1)];

// ---------- Everything a ship's file needs ----------

const sub = (a, b) => a.map((v, k) => v - b[k]);
const len = v => Math.hypot(...v);

// Sun-centred position (AU) and velocity (AU/day) of any ship, the James Webb included.
export function shipAt(id, jd) {
  if (id === 'jwst') {
    const e = earthAt(jd), off = jwstFromEarth(jd).map(v => v / AU_KM);
    const e2 = earthAt(jd + 0.01), off2 = jwstFromEarth(jd + 0.01).map(v => v / AU_KM);
    const pos = e.map((v, k) => v + off[k]);
    return { pos, vel: pos.map((v, k) => (e2[k] + off2[k] - v) / 0.01) };
  }
  return stateAt(id, jd);
}

export function readings(id, jd) {
  const { pos, vel } = shipAt(id, jd);
  const earth = earthAt(jd);
  const fromEarth = id === 'jwst' ? len(jwstFromEarth(jd)) / AU_KM : len(sub(pos, earth));
  return {
    pos, vel,
    sunAU: len(pos),
    earthAU: fromEarth,
    lightSeconds: fromEarth * AU_KM / C_KM_S,
    speedKmS: len(vel) * AU_KM / 86400,
  };
}

// Which way it's heading across the sky, as right ascension (hours) and declination (degrees).
export function heading(id, jd) {
  const [x, y, z] = shipAt(id, jd).vel;
  const ye = y * Math.cos(OBLIQUITY) - z * Math.sin(OBLIQUITY), ze = y * Math.sin(OBLIQUITY) + z * Math.cos(OBLIQUITY);
  const ra = ((Math.atan2(ye, x) / DEG + 360) % 360) / 15;
  return { ra, dec: Math.atan2(ze, Math.hypot(x, ye)) / DEG };
}

// The first date after `from` when f(jd) passes `level` going up, searched a day at a time, or null within `years`.
export function whenAbove(f, level, from, years = 40) {
  let prev = f(from);
  if (prev >= level) return null;
  for (let jd = from + 1; jd <= from + years * 365.25; jd += 1) {
    const v = f(jd);
    if (v >= level) {
      let lo = jd - 1, hi = jd;
      for (let k = 0; k < 30; k++) { const mid = (lo + hi) / 2; if (f(mid) >= level) hi = mid; else lo = mid; }
      return hi;
    }
    prev = v;
  }
  return null;
}
